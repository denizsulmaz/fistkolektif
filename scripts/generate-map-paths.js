/**
 * Pre-generates SVG path strings from world-atlas TopoJSON data.
 * Run: node scripts/generate-map-paths.js
 * Output: src/lib/assets/map-paths.ts
 */

import { geoNaturalEarth1, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';
import { writeFileSync } from 'fs';

const MAP_WIDTH = 960;
const MAP_HEIGHT = 500;

const projection = geoNaturalEarth1()
  .scale(155)
  .translate([MAP_WIDTH / 2, MAP_HEIGHT / 2]);

const pathGenerator = geoPath(projection);

async function generate() {
  console.log('Fetching world atlas data...');
  const response = await fetch('https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json');
  const topology = await response.json();
  const countries = feature(topology, topology.objects.countries);

  const paths = [];
  for (const feat of countries.features) {
    if (feat.id === '010') continue; // Skip Antarctica
    const d = pathGenerator(feat);
    if (d) paths.push(d);
  }

  const output = `// Auto-generated by scripts/generate-map-paths.js — DO NOT EDIT
// Natural Earth 110m country outlines, geoNaturalEarth1 projection
// viewBox: 0 0 ${MAP_WIDTH} ${MAP_HEIGHT}

export const MAP_WIDTH = ${MAP_WIDTH};
export const MAP_HEIGHT = ${MAP_HEIGHT};
export const mapPaths: string[] = ${JSON.stringify(paths)};
`;

  writeFileSync('src/lib/assets/map-paths.ts', output);
  console.log(`Generated ${paths.length} country paths → src/lib/assets/map-paths.ts`);
}

generate().catch(console.error);
